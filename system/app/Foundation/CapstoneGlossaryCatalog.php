    /**
     * @return array{groups: list<array<string, mixed>>, sources: list<array<string, string>>, stats: array<string, mixed>}
     */
    public static function projection(): array
    {
        $groups = self::groups();
        $termCount = 0;
        $dispositionCounts = [
            'canonical' => 0,
            'reconcile' => 0,
            'to-remove' => 0,
            'contextual' => 0,
            'legacy-only' => 0,
        ];

        foreach ($groups as $group) {
            foreach ($group['terms'] as $term) {
                $termCount++;
                $disp = $term['disposition'] ?? 'canonical';
                if (isset($dispositionCounts[$disp])) {
                    $dispositionCounts[$disp]++;
                }
            }
        }

        return [
            'groups' => $groups,
            'sources' => self::sources(),
            'stats' => [
                'groups' => count($groups),
                'terms' => $termCount,
                'sources' => count(self::sources()),
                'dispositions' => $dispositionCounts,
            ],
        ];
    }
